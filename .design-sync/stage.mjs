#!/usr/bin/env node
// Stage packages/design into ds-bundle/ for /design-sync.
//
// packages/ui is Vue 2 + Vuetify and Claude Design binds React components, so
// there is no _ds_bundle.js: this project is the brand book, the tokens, the
// hand-built cards, the atomic cards and canvases rendered from Storybook, and
// the screens (owner's choice, 28 Oct 2026). See NOTES.md.
//
//   node packages/design/tools/build-canvases.js   (refresh the atomic layer first)
//   node .design-sync/stage.mjs                    (from the repo root)
import {
  cpSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync, existsSync,
} from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'packages/design');
const OUT = join(ROOT, 'ds-bundle');
const cfg = JSON.parse(readFileSync(join(ROOT, '.design-sync/config.json'), 'utf8'));

// Generated by tools/build-canvases.js: components/Atom-Alert, Molecule-…, Organism-….
const GENERATED_CARD = /^(Atom|Molecule|Organism)-/;

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const copy = (rel) => cpSync(join(SRC, rel), join(OUT, rel), { recursive: true });

['BRAND.md', 'HANDOFF.md', 'tokens.json', 'tokens.css', 'support.js',
  'android-frame.jsx', 'browser-window.jsx', 'assets'].forEach(copy);
readdirSync(SRC).filter((f) => f.endsWith('.dc.html')).forEach(copy);

// The canvases and their screenshots; manifest.json is build bookkeeping.
const manifest = JSON.parse(readFileSync(join(SRC, 'canvases/manifest.json'), 'utf8'));
const shotCount = readdirSync(join(SRC, 'canvases/shots')).length;
if (shotCount < 100) {
  throw new Error(`canvases/shots has ${shotCount} screenshots; run tools/build-canvases.js to completion first`);
}
cpSync(join(SRC, 'canvases'), join(OUT, 'canvases'), {
  recursive: true, filter: (from) => !from.endsWith('manifest.json'),
});

const cards = readdirSync(join(SRC, 'components'))
  .filter((name) => statSync(join(SRC, 'components', name)).isDirectory());
// The Design System pane names a card after its file, so preview.html would
// label every card "preview". Hand-built cards upload as <Name>.html, generated
// ones as the component's own name (Atom-Alert -> Alert.html): the group
// already says Atoms, Molecules or the organism's page.
const cardName = (dir) => dir.replace(GENERATED_CARD, '');
const cardFile = (dir) => join(OUT, 'components', dir, `${cardName(dir)}.html`);
cards.forEach((dir) => {
  copy(`components/${dir}`);
  renameSync(join(OUT, 'components', dir, 'preview.html'), cardFile(dir));
});

// Designs receive only styles.css and what it @imports.
writeFileSync(join(OUT, 'styles.css'), '/* Routine Notes: the styles entry point */\n@import "./tokens.css";\n');

// README: the conventions header, then the brand book without the parts this
// project does not carry (the build scripts and how to run them).
let readme = readFileSync(join(SRC, 'README.md'), 'utf8').replace(/\r\n/g, '\n');
readme = readme
  .split('\n')
  .filter((line) => !/^\| `tools\//.test(line))
  .join('\n')
  .replace(/\n## Keeping this folder current[\s\S]*$/, '\n')
  .replace('(`preview.html`)', '(`<Name>.html`)');
if (/preview\.html|## Keeping this folder current/.test(readme)) {
  throw new Error('README still mentions preview.html or the build steps; update the trims in stage.mjs');
}
const header = cfg.readmeHeader ? readFileSync(join(ROOT, cfg.readmeHeader), 'utf8') : '';
writeFileSync(join(OUT, 'README.md'), header + readme);

// Every card must open with the @dsCard line or the Design System pane skips
// it, and every image it shows must be in the upload.
const problems = [];
cards.forEach((dir) => {
  const file = cardFile(dir);
  if (!existsSync(file)) { problems.push(`${dir}: no card`); return; }
  const html = readFileSync(file, 'utf8');
  if (!/^<!--\s*@dsCard\s+group="[^"]*"[^>]*-->/.test(html.split('\n', 1)[0])) problems.push(`${dir}: no @dsCard first line`);
  [...html.matchAll(/\bsrc="([^"#?:]+)"/g)].forEach(([, src]) => {
    if (!existsSync(resolve(dirname(file), src))) problems.push(`${dir}: missing ${src}`);
  });
});
if (problems.length) throw new Error(`card problems:\n  ${problems.join('\n  ')}`);

const generated = cards.filter((dir) => GENERATED_CARD.test(dir));
console.log(`staged ${cards.length - generated.length} hand-built cards, ${generated.length} atomic cards, `
  + `${manifest.canvases.length} canvases, ${shotCount} screenshots`);
